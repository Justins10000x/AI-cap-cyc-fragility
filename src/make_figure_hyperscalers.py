"""Figure for the hyperscaler panel. Run from repo root after hyperscalers.py."""
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt

SURF, INK, INK2, MUT = "#fcfcfb", "#0b0b0b", "#52514e", "#8a8984"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
d = pd.read_csv("results/hyperscalers.csv", index_col=0, parse_dates=True)
B = 1e9
ORDER = ["Amazon", "Oracle", "Alphabet", "Meta", "Microsoft"]


def style(ax):
    ax.set_facecolor(SURF)
    for sp in ("top", "right"): ax.spines[sp].set_visible(False)
    for sp in ("left", "bottom"): ax.spines[sp].set_color(MUT)
    ax.tick_params(colors=INK2, labelsize=8.8)
    ax.grid(axis="y", alpha=.18, lw=.6, color=MUT); ax.set_axisbelow(True)


fig = plt.figure(figsize=(13, 10.4), facecolor=SURF)
gs = fig.add_gridspec(2, 2, hspace=.46, wspace=.22, height_ratios=[1.1, 1])

# A: combined capex vs OCF
ax = fig.add_subplot(gs[0, :]); style(ax)
g = d.groupby("quarter")[["capex", "ocf"]].agg(["sum", "count"])
g = g[g[("capex", "count")] == 5].tail(9)
x = np.arange(len(g)); w = .38
cap, ocf = g[("capex", "sum")] / B, g[("ocf", "sum")] / B
ax.bar(x - w / 2, ocf, w, color=AQUA, edgecolor=SURF, lw=2, label="cash generated by operations", zorder=3)
ax.bar(x + w / 2, cap, w, color=ORANGE, edgecolor=SURF, lw=2, label="capex (cash paid)", zorder=3)
for i in range(len(g)):
    r = cap.iloc[i] / ocf.iloc[i]
    ax.text(i, max(cap.iloc[i], ocf.iloc[i]) + 5, f"{r:.0%}", ha="center", fontsize=9.5,
            color=INK, weight="bold" if r > 1 else "normal")
ax.set_xticks(x, [str(q).replace("Q", " Q") for q in g.index], fontsize=9, color=INK2)
ax.set_ylim(0, max(cap.max(), ocf.max()) * 1.2); ax.set_ylabel("$ billions per quarter", fontsize=9.5, color=INK2)
ax.set_title("A. The five hyperscalers combined: capex as a share of the cash their businesses generate",
             fontsize=11, weight="bold", color=INK, loc="left", pad=8)
ax.legend(loc="upper left", fontsize=8.8, frameon=False, labelcolor=INK)

# B: per company, latest quarter vs a year earlier
ax = fig.add_subplot(gs[1, 0]); style(ax)
piv = d.pivot(index="quarter", columns="company", values="capex_pct_ocf")
now, ago = piv.index[-1], piv.index[-5]
x = np.arange(len(ORDER))
ax.bar(x - w / 2, piv.loc[ago, ORDER], w, color=MUT, edgecolor=SURF, lw=2, label=str(ago).replace("Q", " Q"), zorder=3)
ax.bar(x + w / 2, piv.loc[now, ORDER], w, color=ORANGE, edgecolor=SURF, lw=2, label=str(now).replace("Q", " Q"), zorder=3)
for i, c in enumerate(ORDER):
    for off, q in ((-w / 2, ago), (w / 2, now)):
        ax.text(i + off, piv.loc[q, c] + .03, f"{piv.loc[q, c]:.0%}", ha="center", fontsize=8.5, color=INK)
ax.axhline(1, color=INK, lw=1, ls="--", zorder=2)
ax.set_xticks(x, ORDER, fontsize=9, color=INK2)
ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0%}"))
ax.set_ylim(0, piv.loc[[ago, now], ORDER].max().max() * 1.2)
ax.set_title("B. Capex as a share of operating cash flow, by company\n     (dashed line: spends all the cash it earns)", fontsize=11, weight="bold", color=INK, loc="left", pad=8)
ax.legend(loc="upper right", fontsize=8.6, frameon=False, labelcolor=INK)

# C: debt, a year apart
ax = fig.add_subplot(gs[1, 1]); style(ax)
dp = d.pivot(index="quarter", columns="company", values="debt") / B
ax.bar(x - w / 2, dp.loc[ago, ORDER], w, color=MUT, edgecolor=SURF, lw=2, label=str(ago).replace("Q", " Q"), zorder=3)
ax.bar(x + w / 2, dp.loc[now, ORDER], w, color=BLUE, edgecolor=SURF, lw=2, label=str(now).replace("Q", " Q"), zorder=3)
for i, c in enumerate(ORDER):
    for off, q in ((-w / 2, ago), (w / 2, now)):
        ax.text(i + off, dp.loc[q, c] + 3, f"${dp.loc[q, c]:.0f}B", ha="center", fontsize=8.3, color=INK)
ax.set_xticks(x, ORDER, fontsize=9, color=INK2)
ax.set_ylim(0, dp.loc[[ago, now], ORDER].max().max() * 1.18); ax.set_ylabel("$ billions", fontsize=9.5, color=INK2)
ax.set_title("C. Long-term debt, one year apart\n     (definitions differ by company)", fontsize=11, weight="bold", color=INK, loc="left", pad=8)
ax.legend(loc="upper right", fontsize=8.6, frameon=False, labelcolor=INK)

fig.suptitle("Nvidia's biggest buyers now spend more on capex than their businesses generate in cash",
             fontsize=13.5, weight="bold", color=INK, x=.07, ha="left", y=.985)
fig.text(.07, .953, "Source: SEC XBRL company facts; quarters derived from year-to-date filings and reconciled to "
         "annual reports. Cash capex only: leases are excluded. Oracle's quarters end one month earlier.",
         fontsize=8.5, color=INK2)
fig.savefig("results/hyperscalers_v1.png", dpi=145, facecolor=SURF, bbox_inches="tight")
print("saved")
